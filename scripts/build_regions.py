def keep_outer(oldpolys, g, cellm):
    """the rings of a set of touching polygons without the borders between them: a point stays when a point 1.5 cells away in some direction is not ice"""
    mask = fill_polys(g, oldpolys); r = 1.5 * cellm / 111320.0; rl = r / math.cos(math.radians(g.lat0))
    def edge(la, lo): return any(not g.at(mask, la + dy, lo + dx) for dy, dx in ((r, 0), (-r, 0), (0, rl), (0, -rl)))
    return mask, edge


def build_norway(list_only=False):
    allu = lib.arcgis_all(NVE, 15, 'areal_km2 >= 3', 'hovedbreid,hovedbrenavn,areal_km2,minhoyde_moh,makshoyde_moh,forstedatafangstdato', 'nve_bre_ge3.json')
    rows = sorted(({'id': f['properties']['hovedbreid'], 'name': f['properties']['hovedbrenavn'], 'area': f['properties']['areal_km2'], 'f': f} for f in allu), key=lambda r: -r['area'])
    print('largest by NVE:', [(r['id'], r['name'], round(r['area'], 1)) for r in rows[:14]])
    top = [r for r in rows if r['id'] in NO_IDS]
    if sorted(r['id'] for r in rows[:10] if r['id'] is not None) != sorted(NO_IDS): print('WARNING: the ten largest are not NO_IDS:', [r['id'] for r in rows[:10]])
    if list_only: return
    dem = lib.Dem(13)
    units = lib.arcgis_all(NVE, 9, f"hovedbreid IN ({','.join(map(str, NO_IDS))})", 'breid,brenavn,hovedbreid,areal_km2,lengde_m,minhoyde_moh,makshoyde_moh,metode,forstedatafangstdato', 'nve_units_top10.json')
    outlets = []; polys_by = {}
    for r in top:
        polys_by[r['id']] = ll_polys_of(r['f']['geometry'])
    for r in top:
        name = r['name']; hid = r['id']; polys = polys_by[hid]
        rings = [p[0] for p in polys if lib.km2(p[0]) > 0.02]
        print(name, round(r['area'], 1), 'km2,', len(polys), 'parts')
        view = lib.derive_view(rings, dem, label=name)
        us = [u['properties'] for u in units if u['properties']['hovedbreid'] == hid]
        # the unit that holds the tip gives the name of the tongue
        tip = view['tip']; tk = None
        for u in units:
            if u['properties']['hovedbreid'] != hid: continue
            for poly in ll_polys_of(u['geometry']):
                k = 111320.0 * math.cos(math.radians(tip[0]))
                d = min(math.hypot((p[1] - tip[1]) * k, (p[0] - tip[0]) * 111320.0) for p in poly[0])
                if tk is None or d < tk[0]: tk = (d, u['properties'])
        tname = tk[1]['brenavn'].strip() if tk and tk[1].get('brenavn') and tk[1]['brenavn'].strip() not in ('', '<Null>') else None
        dates = sorted({(u.get('metode') or '')[7:15] for u in us if len((u.get('metode') or '')) > 15 and (u['metode'][7:15]).isdigit()})
        # the earlier inventory: units of 1947-1985 that belong to this glacier
        bb = bbox_of(rings, 3000)
        old = lib.arcgis_all(NVE, 16, "produktid='1947_1985'", 'breid,areal_km2,produktid', f"nve_old_{hid}.json",
                             extra=dict(geometry=f'{bb[1]},{bb[0]},{bb[3]},{bb[2]}', geometryType='esriGeometryEnvelope', inSR=4326, spatialRel='esriSpatialRelIntersects'))
        nb = lib.arcgis_all(NVE, 15, 'areal_km2 > 0', 'hovedbreid', f"nve_nb_{hid}.json", extra=dict(geometry=f'{bb[1]},{bb[0]},{bb[3]},{bb[2]}', geometryType='esriGeometryEnvelope', inSR=4326, spatialRel='esriSpatialRelIntersects'))
        lat0, lon0 = (bb[0] + bb[2]) / 2, (bb[1] + bb[3]) / 2
        oc = bv.CELL; bv.CELL = 100.0 if r['area'] > 100 else 50.0
        try:
            g = bv.Grid(lat0, lon0, bb)
            basin = fill_polys(g, polys); near = g.dilate(basin, int(1500 / bv.CELL))
            oth = [p for f in nb if f['properties']['hovedbreid'] != hid for p in ll_polys_of(f['geometry'])]
            others = fill_polys(g, oth) if oth else bytearray(g.w * g.h)
            keep = []
            for f in old:
                for poly in ll_polys_of(f['geometry']):
                    pts = poly[0]; cla = sum(p[0] for p in pts) / len(pts); clo = sum(p[1] for p in pts) / len(pts)
                    if g.at(near, cla, clo) and not g.at(others, cla, clo): keep.append((poly, f['properties']['areal_km2'] or 0))
            mask, edge = keep_outer([k[0] for k in keep], g, bv.CELL)
            lines_old = thin_runs(lines_of([k[0][0] for k in keep], lambda la, lo: edge(la, lo)), g.k)
            a_old = sum(k[1] for k in keep)
            lines_new = thin_runs(lines_of(rings, lambda la, lo: True), g.k)
        finally:
            bv.CELL = oc
        a_new = r['area']
        print(f'  {name}: old {a_old:.1f} km2 ({len(keep)} units, {len(lines_old)} lines), new {a_new:.1f} km2, tongue {tname}')
        outlets.append(dict(id=NO_SLUG[name], name=name, rgi=f'NVE {hid}', note='', tongueName=tname,
                            areaKm2=round(a_new, 1), lengthKm=round(max([u['lengde_m'] or 0 for u in us] + [0]) / 1000, 1),
                            zmin=min(u['minhoyde_moh'] for u in us if u['minhoyde_moh'] is not None), zmax=max(u['makshoyde_moh'] for u in us if u['makshoyde_moh'] is not None), outlineYear=2019,
                            **lib.box_fields(NO_SLUG[name], lat=view['lat'], lon=view['lon'], half=view['half'], tip=view['tip'], strip3d=view['strip3d']),
                            outline=[lib.thin_ll(x, 25) for x in rings], units=len(us), areas=[dict(year=1966, label='1947–1985', km2=round(a_old, 1)), dict(year=2019, label='2018–2019', km2=round(a_new, 1))],
                            outlines=dict(lia=dict(year=1966, label='1947–1985', date='', lines=lines_old, areaInBasinKm2=round(a_old, 1)),
                                          latest=dict(year=2019, label='2018–2019, Sentinel-2', date=(f'{dates[0]} to {dates[-1]}' if dates else ''), lines=lines_new, areaInBasinKm2=round(a_new, 1)))))
    basins = []
    for r in rows:
        if r['id'] in NO_IDS or r['area'] < 3: continue
        basins.append(dict(rgi='', name=r['name'] or '', areaKm2=round(r['area'], 1), outline=[lib.thin_ll(p[0], 60) for p in ll_polys_of(r['f']['geometry']) if lib.km2(p[0]) > 0.1]))
    tot = sum(r['area'] for r in rows)
    data = dict(source='NVE glacier inventory 2018-2019 (Andreassen et al. 2022) and the inventory of 1947-1985, Norwegian Water Resources and Energy Directorate',
                icecap=dict(name='Norway', areaKm2=round(tot), entities=len(rows)), outlets=outlets, basins=basins)
    write_js(os.path.join(OUTDIR, 'norway.js'), data, 'the ten largest glaciers of mainland Norway')



