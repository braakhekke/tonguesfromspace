#!/usr/bin/env python3
"""
build_regions.py - the ice caps and glaciers of three more regions -> data/iceland.js, data/svalbard.js, data/norway.js

Each file sets window.REGION_ICE in the shape of data/vatnajokull.js (see build_vatnajokull.py): `outlets` (the ten glaciers that can be chosen), `basins` (the other ice around them, drawn
white on the overview), `icecap` (the region's totals). Exactly ten glaciers per region, the ten largest by area (a glacier = an ice cap or a glacier complex, see below).

    python3 scripts/build_regions.py iceland      Iceland without Vatnajökull
    python3 scripts/build_regions.py svalbard     the Svalbard archipelago
    python3 scripts/build_regions.py norway       mainland Norway
    python3 scripts/build_regions.py --list REGION   only list the candidates

Sources (open data; the credits are in js/00-regions.js and the Sources list of the page)
  Iceland   Randolph Glacier Inventory 6.0 (GLIMS WFS) for the ice caps (basins that touch form one ice cap: icecap_lib.clusters), the outlines of the Icelandic Met Office (WFS geo.vedur.is,
            Hannesdóttir et al. 2020, CC BY 4.0): the Little Ice Age maximum (about 1890) and the Sentinel-2 outline of September 2025, cut to the region of each ice cap like build_vatnajokull.py
  Norway    NVE, the Norwegian Water Resources and Energy Directorate (kart.nve.no, Bre2): the glaciers of the 2018-2019 glacier inventory from Sentinel-2 images (Andreassen et al. 2022; a glacier
            = the units that hang together, `hovedbre`), the earlier inventory of 1947-1985 (maps and aerial photographs; the year differs by glacier), length and heights of the units
  Svalbard  Norwegian Polar Institute (geodata.npolar.no): glacier outlines of 1936-1972, 1990, 2001-2010 and 2020 (Sentinel-2), one unit per glacier basin, the same ident in every epoch;
            names, definitions and name origins from the NPI place names (api.npolar.no/placename)
The tip of each glacier (lowest point of its outline), its 3D strip and its picture box come from icecap_lib.derive_view with the Mapterhorn terrain tiles. Standard library and Pillow.
"""
