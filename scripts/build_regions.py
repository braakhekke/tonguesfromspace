def iceland_caps():
    feats = lib.rgi_features('Iceland')
    comps = lib.clusters(feats, lambda f: f['geometry'], 150.0)
    caps = []
    for c in comps:
        a = sum(feats[i]['properties']['AREA'] for i in c)
        zmins = [feats[i]['properties']['ZMIN'] for i in c if feats[i]['properties']['ZMIN'] > -900]
        cy = sum(feats[i]['properties']['CENLAT'] * feats[i]['properties']['AREA'] for i in c) / a
        cx = sum(feats[i]['properties']['CENLON'] * feats[i]['properties']['AREA'] for i in c) / a
        caps.append(dict(idx=c, area=a, lat=cy, lon=cx, zmin=min(zmins) if zmins else None, zmax=max(feats[i]['properties']['ZMAX'] for i in c),
                         length=max(feats[i]['properties']['LMAX'] for i in c), n=len(c)))
    caps.sort(key=lambda c: -c['area'])
    return feats, caps


def build_iceland(list_only=False):
    feats, caps = iceland_caps()
    cx = 0
    chosen = []
    for c in caps:
        if c['area'] > 5000: continue      # Vatnajökull (one cluster of 8,000 km²)
        chosen.append(c)
    for c in chosen[:16]: print(f"  {c['area']:7.1f} km2  {c['n']:3d} basins  {c['lat']:.2f} {c['lon']:.2f}  zmin {c['zmin']}  {[a[1] for a in IS_ANCHORS if abs(a[2] - c['lat']) < .25 and abs(a[3] - c['lon']) < .5]}")
    if list_only: return
    # name the ten largest by their anchor; every anchor is used once
    top = []
    for c in chosen:
        best = min(IS_ANCHORS, key=lambda a: (a[2] - c['lat']) ** 2 + ((a[3] - c['lon']) * math.cos(math.radians(c['lat']))) ** 2)
        d = math.hypot(best[2] - c['lat'], (best[3] - c['lon']) * math.cos(math.radians(c['lat']))) * 111.32
        if d < 15 and best[0] not in [t['id'] for t in top]: c.update(id=best[0], name=best[1]); top.append(c)
        if len(top) == 10: break
    if len(top) < 10: sys.exit('fewer than ten named ice caps')
    print('the ten:', [(t['name'], round(t['area'])) for t in top])
    dem = lib.Dem(12)      # Mapterhorn has no finer tiles over Iceland
    others_all = [c for c in chosen if c not in top]
    vat = [c for c in caps if c['area'] > 5000]
    outlets = []
    all_clusters = caps
    for t in top:
        print(t['name'])
        ents = [feats[i] for i in t['idx']]
        rings = []
        for f in ents: rings += ring_set(f['geometry'], 25)
        view = lib.derive_view(rings, dem, label=t['name'])
        # the entity with the lowest point under the tip gives the name of the tongue
        tipm = lib.merc(*view['tip'])
        near = min(ents, key=lambda f: min((x - tipm[0]) ** 2 + (y - tipm[1]) ** 2 for poly in (f['geometry']['coordinates'] if f['geometry']['type'] == 'MultiPolygon' else [f['geometry']['coordinates']]) for x, y in poly[0]))
        tname = IS_NAMES.get(near['properties']['NAME'].split(' (')[0].strip(), None) or (near['properties']['NAME'] or '').replace('oe', 'ö') or None
        # the outlines of other dates: lines inside the region of the ice cap
        outl = epoch_outlines_iceland(t, feats, caps, rings)
        t.update(rings=rings, view=view, tongue=tname, outlines=outl)
        zmin = t['zmin']
        outlets.append(dict(id=t['id'], name=t['name'], rgi=ents[0]['properties']['RGIID'], note='', tongueName=tname,
                            areaKm2=round(t['area'], 1), lengthKm=round(t['length'] / 1000, 1), zmin=zmin, zmax=t['zmax'], outlineYear=int(max(f['properties']['BGNDATE'][:4] for f in ents)),
                            **lib.box_fields(t['id'], lat=view['lat'], lon=view['lon'], half=view['half'], tip=view['tip'], strip3d=view['strip3d']),
                            outline=[lib.thin_ll(r, 25) for r in rings if lib.km2(r) > 0.02], outlines=outl,
                            entities=len(ents)))
    # the other ice caps of the region, for the overview
    basins = []
    for c in caps:
        if c in top or c['area'] < 3 or c['area'] > 5000: continue
        rr = []
        for i in c['idx']: rr += ring_set(feats[i]['geometry'], 120)
        basins.append(dict(rgi='', name='', areaKm2=round(c['area'], 1), outline=[r for r in rr if lib.km2(r) > 0.1]))
    tot = sum(c['area'] for c in caps if c['area'] < 5000)
    data = dict(source='Randolph Glacier Inventory 6.0, region 06 Iceland (RGI Consortium 2017), via GLIMS; outlines from about 2000 (Vatnajökull is a region of its own)',
                icecap=dict(name='Iceland', areaKm2=round(tot), entities=len([c for c in caps if c['area'] < 5000])), outlets=outlets, basins=basins)
    write_js(os.path.join(OUTDIR, 'iceland.js'), data, 'the ten largest ice caps of Iceland outside Vatnajökull')


def epoch_outlines_iceland(t, feats, caps, rings):
    """{lia, latest}: the Icelandic Met Office outlines cut to the region of the ice cap (its RGI area plus 3 km, without other ice caps)"""
    bb = bbox_of(rings, 6000)
    lat0, lon0 = (bb[0] + bb[2]) / 2, (bb[1] + bb[3]) / 2
    old_cell = bv.CELL
    bv.CELL = 100.0 if t['area'] > 100 else 50.0
    try:
        g = bv.Grid(lat0, lon0, bb)
        basin = fill_rings(g, rings)
        near = g.dilate(basin, int(3000 / bv.CELL))
        oth = []
        for c in caps:
            if c is t: continue
            for i in c['idx']:
                geom = feats[i]['geometry']
                cen = (feats[i]['properties']['CENLAT'], feats[i]['properties']['CENLON'])
                if bb[0] - .1 < cen[0] < bb[2] + .1 and bb[1] - .2 < cen[1] < bb[3] + .2: oth += ring_set(geom, 60)
        others = fill_rings(g, oth) if oth else bytearray(g.w * g.h)
        region = bytearray(1 if n and not x else 0 for n, x in zip(near, others))
        for i in range(len(basin)):
            if basin[i]: region[i] = 1
        out = {}
        for key, (layer, year, label) in bv.IMO_EPOCHS.items():
            rr, date = bv.imo_polygons(layer, [bb[1], bb[0], bb[3], bb[2]])
            runs = lines_of(rr, lambda la, lo: g.at(region, la, lo))
            lines = thin_runs(runs, g.k)
            ice = fill_rings(g, rr) if False else g.fill(rr)
            if key == 'latest': area = sum(1 for a, b in zip(ice, basin) if a and b) * bv.CELL * bv.CELL / 1e6
            else: area = sum(1 for a, b in zip(ice, region) if a and b) * bv.CELL * bv.CELL / 1e6
            out[key] = dict(year=year, label=label, date=date, lines=lines, areaInBasinKm2=round(area, 1))
            print(f"  {t['name']} {label}: {len(lines)} lines, {sum(len(l) for l in lines)} points, {area:.0f} km2")
        return out
    finally:
        bv.CELL = old_cell



