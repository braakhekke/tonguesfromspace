# ---------- rasters of a region (the Grid of build_vatnajokull.py, with one fill per ring so that touching polygons do not cancel) ----------
def fill_rings(g, rings):
    out = bytearray(g.w * g.h)
    for r in rings:
        m = g.fill([r])
        for i, v in enumerate(m):
            if v: out[i] = 1
    return out


def fill_polys(g, polys):
    """polys: list of polygons, each a list of rings ([lat, lon] lists, outer first): even-odd inside a polygon (holes), union between polygons"""
    out = bytearray(g.w * g.h)
    for p in polys:
        m = g.fill(p)
        for i, v in enumerate(m):
            if v: out[i] = 1
    return out


def bbox_of(rings, pad_m=0):
    pts = [p for r in rings for p in r]
    la, lo = [p[0] for p in pts], [p[1] for p in pts]; mid = (min(la) + max(la)) / 2
    d_la, d_lo = pad_m / 111320.0, pad_m / (111320.0 * math.cos(math.radians(mid)))
    return (min(la) - d_la, min(lo) - d_lo, max(la) + d_la, max(lo) + d_lo)      # south, west, north, east


def lines_of(rings, keep):
    """pieces of closed rings ([lat, lon]) whose points `keep` accepts, as open runs of 3+ points"""
    runs = []
    for ring in rings:
        run = []
        for la, lo in ring + ring[:1]:
            if keep(la, lo): run.append((la, lo))
            else:
                if len(run) > 2: runs.append(run)
                run = []
        if len(run) > 2: runs.append(run)
    return runs


def thin_runs(runs, k):
    return [l for l in ([[round(a, 5), round(b, 5)] for a, b in bv.dp_ll(r, 15, k)] for r in runs) if len(l) > 2]


def poly_stats(polys):
    """(outer rings, area km²) of GeoJSON-like polygons given as lists of rings ([lat, lon])"""
    return sum(lib.km2(p[0]) - sum(lib.km2(h) for h in p[1:]) for p in polys)


def ring_set(g, tol=25):
    """outer rings of a Web Mercator (Multi)Polygon thinned and as [lat, lon] (RGI)"""
    out = []
    polys = g['coordinates'] if g['type'] == 'MultiPolygon' else [g['coordinates']]
    for poly in polys:
        r = bv.ring_out(poly[0], tol)
        if r: out.append(r)
    return out


def ll_polys_of(geom):
    """a GeoJSON (Multi)Polygon in WGS84 as polygons of [lat, lon] rings (outer first)"""
    polys = geom['coordinates'] if geom['type'] == 'MultiPolygon' else [geom['coordinates']]
    return [[[[lat, lon] for lon, lat in ring] for ring in poly] for poly in polys]


def write_js(path, data, note):
    with open(path, 'w', encoding='utf-8') as fh:
        fh.write(f'// generated by scripts/build_regions.py - do not edit by hand\n// {note}\nwindow.REGION_ICE = ' + json.dumps(data, ensure_ascii=False, separators=(',', ':')) + ';\n')
    print(f'wrote {path} ({os.path.getsize(path) / 1024:.0f} kB)')


def basin_list(items, min_km2, tol_m):
    """the other ice of the region for the overview: [{name, areaKm2, outline: [rings]}]"""
    out = []
    for it in items:
        if it['areaKm2'] < min_km2: continue
        out.append(dict(rgi=it.get('id', ''), name=it.get('name', ''), areaKm2=round(it['areaKm2'], 1),
                        outline=[lib.thin_ll(r, tol_m) for r in it['rings'] if lib.km2(r) > 0.05]))
    return out


