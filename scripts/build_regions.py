def npi_unit(layer, ident):
    """polygons (lists of [lat, lon] rings, outer first) and the record of one glacier unit in one epoch; the unit may be several polygons"""
    fs = lib.arcgis_all(NPI, layer, f'IDENT >= {ident - 0.0005} AND IDENT <= {ident + 0.0005}', '*', f'npi_{layer}_{ident}.json')
    return [f for f in fs if abs((f['properties'].get('IDENT') or 0) - ident) < 1e-6]


def npi_placename(name):
    d = json.loads(lib.http('https://api.npolar.no/placename/?' + __import__('urllib.parse').parse.urlencode(dict(q=name, format='json', limit=10))))
    for e in d['feed']['entries']:
        if e['name']['@value'] == name and e.get('terrain', {}).get('en') == 'glacier':
            t = e.get('texts', {})
            return dict(ident=e['ident'], definition=(t.get('definition') or {}).get('en', ''), origin=(t.get('origin') or {}).get('en', ''), lat=e['latitude'], lon=e['longitude'])
    return None


def build_svalbard(list_only=False):
    allf = lib.arcgis_all(NPI, 4, '1=1', 'IDENT,NAME,YEAR,AREA,TIDEWATER,SOURCE', 'npi_4_all.json')
    rows = sorted(allf, key=lambda f: -(f['properties']['AREA'] or 0))
    print('largest 2020 units:', [(f['properties']['IDENT'], f['properties']['NAME'], round(f['properties']['AREA'])) for f in rows[:16]])
    if list_only: return
    dem = lib.Dem(12)
    outlets = []
    for ident, slug, name in SV:
        u4 = npi_unit(4, ident)
        if not u4: sys.exit(f'{name}: no 2020 polygon')
        polys = [p for f in u4 for p in ll_polys_of(f['geometry'])]
        a2020 = sum(f['properties']['AREA'] for f in u4)
        rings = [p[0] for p in polys if lib.km2(p[0]) > 0.02]
        print(name, round(a2020, 1))
        view = lib.derive_view(rings, dem, label=name)
        areas, epochs = [], {}
        for layer in (1, 2, 3, 4):
            fs = u4 if layer == 4 else npi_unit(layer, ident)
            if not fs: continue
            yr = int(fs[0]['properties'].get('YEAR') or fs[0]['properties'].get('YEAR_') or 0)
            ar = sum(lib.km2(p[0]) - sum(lib.km2(h) for h in p[1:]) for f in fs for p in ll_polys_of(f['geometry'])) if layer != 4 else a2020
            areas.append(dict(year=yr, label=NPI_LAYERS[layer], km2=round(ar, 1)))
            epochs[layer] = (yr, fs)
        l3 = (epochs.get(3) or (0, []))[1]
        p3 = l3[0]['properties'] if l3 else {}
        oldk = 1 if 1 in epochs else 2 if 2 in epochs else None
        bbx = bbox_of(rings, 500); k = 111320.0 * math.cos(math.radians((bbx[0] + bbx[2]) / 2))
        def lines_for(fs): return thin_runs([r + r[:1] for f in fs for p in ll_polys_of(f['geometry']) for r in p[:1] if lib.km2(r) > 0.02], k)
        outl = {}
        if oldk:
            yr, fs = epochs[oldk]
            outl['lia'] = dict(year=yr, label=str(yr), date='', lines=lines_for(fs), areaInBasinKm2=[a for a in areas if a['label'] == NPI_LAYERS[oldk]][0]['km2'])
        outl['latest'] = dict(year=2020, label='2020, Sentinel-2', date='2020', lines=lines_for(u4), areaInBasinKm2=round(a2020, 1))
        pn = npi_placename(name)
        print('  ', [(a['label'], a['km2']) for a in areas], 'placename' if pn else 'NO placename')
        outlets.append(dict(id=slug, name=name, rgi=f'NPI {ident}', note='', tongueName=None, placename=pn, tidewater=bool(u4[0]['properties'].get('TIDEWATER')),
                            areaKm2=round(a2020, 1), lengthKm=round((p3.get('LENGTH') or 0) / 1000, 1), zmin=round(p3.get('minZ') or 0), zmax=round(p3.get('maxZ') or 0), outlineYear=int(epochs[3][0]) if 3 in epochs else 2020,
                            **lib.box_fields(slug, lat=view['lat'], lon=view['lon'], half=view['half'], tip=view['tip'], strip3d=view['strip3d']),
                            outline=[lib.thin_ll(r, 25) for r in rings], areas=areas, outlines=outl))
    ids = {i for i, _, _ in SV}
    basins = []
    for f in rows:
        pr = f['properties']
        if any(abs(pr['IDENT'] - i) < 1e-6 for i in ids) or (pr['AREA'] or 0) < 100: continue
        nm = pr['NAME'] or ''
        basins.append(dict(rgi='', name=nm, areaKm2=round(pr['AREA'], 1), outline=[lib.thin_ll(p[0], 120) for p in ll_polys_of(f['geometry']) if lib.km2(p[0]) > 0.5]))
    tot = sum(f['properties']['AREA'] or 0 for f in allf)
    data = dict(source='Norwegian Polar Institute glacier outlines of Svalbard 1936-1972, 1990, 2001-2010 and 2020 (geodata.npolar.no)',
                icecap=dict(name='Svalbard', areaKm2=round(tot), entities=len(allf)), outlets=outlets, basins=basins)
    write_js(os.path.join(OUTDIR, 'svalbard.js'), data, 'ten large glaciers of the Svalbard archipelago')


