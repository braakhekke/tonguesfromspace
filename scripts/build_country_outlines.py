#!/usr/bin/env python3
"""Country outlines for the map inset of the downloads (data/country-outlines.js).
Source: Natural Earth 1:10m Admin 0 Countries (public domain), simplified here (Douglas-Peucker, ~0.01 deg).
Usage: build_country_outlines.py <ne_10m_admin_0_countries.geojson>"""
import json, sys, math

TOL = 0.012

def dp(pts, tol):
    if len(pts) < 3: return pts
    a, b = pts[0], pts[-1]; dx, dy = b[0]-a[0], b[1]-a[1]; n = math.hypot(dx, dy) or 1e-12
    k, dm = 0, 0
    for i in range(1, len(pts)-1):
        d = abs(dy*(pts[i][0]-a[0]) - dx*(pts[i][1]-a[1])) / n
        if d > dm: k, dm = i, d
    if dm <= tol: return [a, b]
    return dp(pts[:k+1], tol)[:-1] + dp(pts[k:], tol)

def rings(geom):
    polys = [geom['coordinates']] if geom['type'] == 'Polygon' else geom['coordinates']
    return [p[0] for p in polys]          # outer rings only

def pack(rs):
    out = []
    for r in rs:
        pts = [(x, y) for x, y in r]; h = len(pts)//2      # a closed ring is cut in two first (Douglas-Peucker needs two different ends)
        s = dp(pts[:h+1], TOL)[:-1] + dp(pts[h:], TOL)
        if len(s) >= 4: out.append([[round(y, 3), round(x, 3)] for x, y in s])      # [lat, lon]
    return out

d = json.load(open(sys.argv[1]))
by = {f['properties']['ADM0_A3']: f['geometry'] for f in d['features']}
def mean(r): return sum(p[0] for p in r)/len(r), sum(p[1] for p in r)/len(r)
nor = rings(by['NOR'])
res = {
  'ch': pack(rings(by['CHE'])),
  'is': pack(rings(by['ISL'])),
  'no-mainland': pack([r for r in nor if mean(r)[1] < 72 and mean(r)[0] < 33 and mean(r)[0] > 3 or (mean(r)[1] < 72 and mean(r)[1] > 57)]),
  'no-svalbard': pack([r for r in nor if mean(r)[1] > 74 and mean(r)[0] > 9]),
}
res['no-mainland'] = [r for r in res['no-mainland'] if sum(p[0] for p in r)/len(r) < 72]
with open('data/country-outlines.js', 'w') as f:
    f.write('// generated by scripts/build_country_outlines.py - do not edit by hand. Natural Earth 1:10m Admin 0 Countries (public domain), simplified. [lat, lon] rings per region id.\n')
    f.write('window.COUNTRY_OUTLINES = ' + json.dumps(res, separators=(',', ':')) + ';\n')
print({k: (len(v), sum(len(r) for r in v)) for k, v in res.items()})
