#!/usr/bin/env python3
"""data/france.js (window.REGION_ICE) for the region 'fr' (France): Mer de Glace, from the onboarding session experiments/onboard/mer-de-glace/ (local, gitignored).

What is in it: the dated GLIMS outlines of the session (oldest 1967, newest 2015 are the two outlines of the page), the areas of all dated outlines as the database states them (rounded to 2 decimals),
the tongue tip, the picture box, the strip, and the highest and lowest point of the 2015 outline COMPUTED from the IGN LiDAR HD surface model (the page says so). Texts are in js/07b-icecap-texts.js.
Usage (repo root, project venv with shapely, pyproj, numpy): experiments/aletsch-yearly-dem/.venv/bin/python scripts/build_france.py
Then: `npx tsx walkthrough/cli.ts import-site fr` -> `npm run walkthrough -- export` (data/boxes.js, data/scenes.json, worker/glacier-index.json), `python3 scripts/sync_worker_centres.py`.
"""
import json, os, math
import numpy as np
from shapely.geometry import shape
from shapely.ops import transform as T
from pyproj import Transformer
from rasterio.features import rasterize
from rasterio.transform import from_origin
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
S = os.path.join(ROOT, 'experiments', 'onboard', 'mer-de-glace')
sess = json.load(open(os.path.join(S, 'session.json')))
feat = {f['properties']['key']: f for f in json.load(open(os.path.join(S, 'outlines.geojson')))['features']}
ring = lambda r: [[round(y, 5), round(x, 5)] for x, y in r]
def lines(f):
    g = f['geometry']; polys = g['coordinates'] if g['type'] == 'MultiPolygon' else [g['coordinates']]
    return [ring(r) for p in polys for r in p]
OLD, NEW = 'glims-1967-lgge-0', 'glims-2015-uzh-9'
new, old = feat[NEW], feat[OLD]
w = np.load(os.path.join(S, 'elevation', 'lidar-mns-5m-l93.npz')); Z = w['z'].astype('float64'); x0, y1, res = float(w['x0']), float(w['y1']), float(w['cell'])
t = Transformer.from_crs(4326, 2154, always_xy=True).transform
m = rasterize([(T(t, shape(new['geometry'])).buffer(0), 1)], out_shape=Z.shape, transform=from_origin(x0, y1, res, res), dtype='uint8').astype(bool) & np.isfinite(Z) & (Z > 0)
zmin, zmax = int(round(float(np.percentile(Z[m], 0.1)))), int(round(float(np.percentile(Z[m], 99.9))))   # 0.1 / 99.9 percentile: single noisy cells do not set the extremes
st = sess['steps']['strip']['params']; tip = st['tip']; bx = st['box']
dated = sorted((f['properties'] for f in feat.values() if f['properties']['key'].startswith('glims-')), key=lambda p: (p['date'], p['key']))
WHO = {'LGGE': 'LGGE', 'FAU': 'FAU', 'UZH': 'University of Zurich'}      # the group of each GLIMS record, from its key (glims-<year>-<group>-<n>)
areas = [{'year': int(p['date'][:4]), 'label': p['date'][:4] + ' (' + WHO[p['key'].split('-')[2].upper()] + ')', 'km2': round(p['area_km2'], 2)} for p in dated]
mid = (bx[0][0] + bx[1][0]) / 2
outlet = {
    'id': 'mer-de-glace', 'name': 'Mer de Glace', 'rgi': 'RGI60-11.03643', 'note': '', 'tongueName': '',
    'areaKm2': round(new['properties']['area_km2'], 2), 'lengthKm': 0, 'zmin': zmin, 'zmax': zmax, 'hNote': 'calculated here from the IGN LiDAR HD surface model, inside the outline of 2015', 'hSrc': 'fr_ign', 'outlineYear': 2015,
    'lat': round(mid, 5), 'lon': round((bx[0][1] + bx[1][1]) / 2, 5), 'half': round((bx[1][1] - bx[0][1]) / 2 * 111.32 * math.cos(math.radians(mid)), 7), 'halfH': round((bx[1][0] - bx[0][0]) / 2 * 111.32, 7), 'box': bx, 'tip': tip,
    'strip3d': {'azimuth': st['azimuth'], 'half': st['half'], 'back': st['back'], 'up': st['up'], 'cell': 16},
    'outline': lines(new), 'units': 1, 'areas': areas,
    'outlines': {'lia': {'year': 1967, 'label': '1967, LGGE (GLIMS)', 'date': old['properties']['date'], 'lines': lines(old)}, 'latest': {'year': 2015, 'label': '2015, University of Zurich (GLIMS)', 'date': new['properties']['date'], 'lines': lines(new)}},
}
data = {'source': 'GLIMS Glacier Database: dated outlines 1967 to 2015; heights computed from the IGN LiDAR HD surface model',
        'icecap': {'name': 'France', 'areaKm2': 0, 'entities': 1}, 'outlets': [outlet], 'basins': []}
out = os.path.join(ROOT, 'data', 'france.js')
open(out, 'w', encoding='utf-8').write('// generated by scripts/build_france.py - do not edit by hand\n// Mer de Glace, France\nwindow.REGION_ICE = ' + json.dumps(data, ensure_ascii=False, separators=(',', ':')) + ';\n')
print('data/france.js', os.path.getsize(out) // 1024, 'KB; zmin', zmin, 'zmax', zmax, 'areas', [(a['year'], a['km2']) for a in areas], 'rings', len(outlet['outline']))
