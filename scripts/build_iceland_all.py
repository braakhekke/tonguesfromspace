#!/usr/bin/env python3
"""build_iceland_all.py - Iceland as one region: data/vatnajokull.js + data/iceland.js -> data/iceland-all.js

The two builders (build_vatnajokull.py, build_regions.py iceland) stay as they are and their files stay the inputs of the other scripts (terrain, Landsat, trails, oldest pictures, cloud
masks, the walkthrough's records: records of the two record regions is-vatnajokull and is-rest). The page reads only this file (REGION 'is' in js/regions.js). Nothing is computed
here except the joining: outlets and basins are put one after the other (the outlets of Vatnajökull first, in the order of their files), and each part keeps its own figures in
`icecap.parts` (the area and number of basins as the inventory gives them for that part); an outlet of Vatnajökull gets `canton: 'Vatnajökull ice cap'`.

    python3 scripts/build_iceland_all.py            writes data/iceland-all.js (run it after build_vatnajokull.py, build_regions.py iceland and build_cap_images.py)
"""
import json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
DATA = os.path.join(os.path.dirname(HERE), 'data')
MARK = 'window.REGION_ICE = '


def read(name):
    t = open(os.path.join(DATA, name), encoding='utf-8').read()
    return json.loads(t[t.index(MARK) + len(MARK):].strip().rstrip(';'))


def main():
    vat, rest = read('vatnajokull.js'), read('iceland.js')
    ids = [o['id'] for o in vat['outlets'] + rest['outlets']]
    if len(ids) != len(set(ids)):
        sys.exit('an outlet id is in both files: ' + ', '.join(sorted({i for i in ids if ids.count(i) > 1})))
    for o in vat['outlets']:
        o['canton'] = 'Vatnajökull ice cap'
    data = {
        'source': 'Randolph Glacier Inventory 6.0, region 06 Iceland (RGI Consortium 2017), via GLIMS; outlines from about 2000',
        'icecap': {'name': 'Iceland', 'parts': [{'id': 'vatnajokull', **vat['icecap']}, {'id': 'rest', **rest['icecap']}]},
        'outlets': vat['outlets'] + rest['outlets'],
        'basins': vat['basins'] + rest['basins'],
    }
    out = os.path.join(DATA, 'iceland-all.js')
    with open(out, 'w', encoding='utf-8') as f:
        f.write('// generated by scripts/build_iceland_all.py from data/vatnajokull.js and data/iceland.js - do not edit by hand\n')
        f.write(MARK + json.dumps(data, ensure_ascii=False, separators=(',', ':')) + ';\n')
    print(f'{out}: {len(data["outlets"])} outlets ({len(vat["outlets"])} Vatnajökull + {len(rest["outlets"])} rest), {len(data["basins"])} basins')


if __name__ == '__main__':
    main()
