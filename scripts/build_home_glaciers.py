#!/usr/bin/env python3
"""Writes data/home-glaciers.js for the landing page (home.html): one record per glacier of every region (and, with `parent`, one per outlet of an ice cap), `window.HOME_GLACIERS`.
id = the id the dashboard takes in `#g=` (Swiss: the site id, see SITE_ID in audit_glaciers.py), name, region, area in km2 as the data
files state it (Swiss: SGI2023 `area_km2`; the others: `areaKm2` of the outlet), lat/lon = the tongue tip of data/boxes.js.
Also rewrites the marked block (regions) of gallery.html. Standard library only."""
import json, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SITE_ID = {'B36-26': 'aletsch', 'B56-07': 'gorner', 'B40-07': 'fiescher', 'A54g-11': 'unteraar', 'B83-03': 'corbassiere', 'B57-05': 'zmutt',
           'B43-03': 'rhone', 'B56-03': 'sgi-B56-03', 'B53-04': 'sgi-B53-04', 'A54e-24': 'trift'}
REGION_FILES = [('is-vatnajokull', 'vatnajokull'), ('is-rest', 'iceland'), ('no-mainland', 'norway'), ('no-svalbard', 'svalbard')]

def window(path, name):
    s = open(os.path.join(ROOT, path), encoding='utf-8').read()
    return json.JSONDecoder().raw_decode(s[s.index('{', s.index(name)):])[0]

boxes = window('data/boxes.js', 'window.GLACIER_BOXES')['glaciers']
out = []
swiss = {g['id']: g for g in window('data/glaciers.js', 'window.GLACIER_DATA')['glaciers']}
for inv, site in SITE_ID.items():
    b = boxes[inv]
    out.append({'id': site, 'name': b['name'], 'region': 'ch', 'area': swiss[inv]['area_km2'], 'tip': b['tip']})
for region, f in REGION_FILES:
    for o in window('data/%s.js' % f, 'window.REGION_ICE')['outlets']:
        out.append({'id': o['id'], 'name': o['name'], 'region': region, 'area': o['areaKm2'], 'tip': boxes[o['id']]['tip']})
        for k, sb in enumerate(o.get('subs') or []):      # the outlets of an ice cap are glaciers of their own on the map: id '<cap>~<k>', the dashboard opens the cap with the outlet in focus (#g=<cap>&sub=<k>)
            out.append({'id': '%s~%d' % (o['id'], k), 'name': sb['name'], 'region': region, 'area': sb['areaKm2'], 'tip': sb['tip'], 'parent': o['id'], 'sub': k, 'approx': bool(sb.get('approx'))})

# the outlines the front page draws when a glacier is chosen (data/home-outlines.js, loaded on the first choice): the catchment of an ice-cap outlet (RGI 6.0 basin
# or the inventory unit of its region) or the Swiss 2023 outline. Only a thinning of the vertices (Douglas-Peucker, 0.0008 degrees, about 90 m): points are kept as they are, none is moved or rounded.
def dp(pts, tol):
    if len(pts) < 3: return pts
    keep = [False] * len(pts); keep[0] = keep[-1] = True; stack = [(0, len(pts) - 1)]
    while stack:
        a, b = stack.pop(); (ay, ax), (by, bx) = pts[a], pts[b]; dy, dx = by - ay, bx - ax; n = (dy * dy + dx * dx) ** .5 or 1e-12; best, bi = -1, a
        for i in range(a + 1, b):
            d = abs(dy * (pts[i][1] - ax) - dx * (pts[i][0] - ay)) / n
            if d > best: best, bi = d, i
        if best > tol: keep[bi] = True; stack += [(a, bi), (bi, b)]
    return [p for p, k in zip(pts, keep) if k]
def ring_dp(r, tol):      # a closed ring has no chord from first to last point: thin its two halves
    if len(r) > 3 and r[0] == r[-1]: m = len(r) // 2; return dp(r[:m + 1], tol)[:-1] + dp(r[m:], tol)
    return dp(r, tol)
def thin(rings): return [r for r in (ring_dp(r, 0.0008) for r in rings) if len(r) >= 4]
outlines = {}
for inv, site in SITE_ID.items():
    geom = swiss[inv]['outline']
    polys = geom['coordinates'] if geom['type'] == 'MultiPolygon' else [geom['coordinates']]
    outlines[site] = thin([[[y, x] for x, y in poly[0]] for poly in polys])      # GeoJSON [lon, lat] -> [lat, lon]; the outer ring of every part
for region, f in REGION_FILES:
    for o in window('data/%s.js' % f, 'window.REGION_ICE')['outlets']:
        outlines[o['id']] = thin(o['outline'])
        for k, sb in enumerate(o.get('subs') or []): outlines['%s~%d' % (o['id'], k)] = thin(sb['outline'])
op = os.path.join(ROOT, 'data', 'home-outlines.js')
open(op, 'w', encoding='utf-8').write('// generated by scripts/build_home_glaciers.py - do not edit by hand\nwindow.HOME_OUTLINES = ' + json.dumps(outlines, separators=(',', ':')) + ';\n')
print(len(outlines), 'outlines ->', op, round(os.path.getsize(op) / 1024), 'kB')

path = os.path.join(ROOT, 'data', 'home-glaciers.js')
open(path, 'w', encoding='utf-8').write('// generated by scripts/build_home_glaciers.py - do not edit by hand\nwindow.HOME_GLACIERS = ' + json.dumps(out, ensure_ascii=False, separators=(',', ':')) + ';\n')
print(len(out), 'glaciers ->', path)

# gallery.html needs the same ids to tell the region of a shared item (items carry only the glacier id): rewrite its marked block
REGION_NAMES = [('ch', 'Switzerland'), ('is-vatnajokull', 'Vatnajökull'), ('is-rest', 'Rest of Iceland'), ('no-mainland', 'Norway'), ('no-svalbard', 'Svalbard')]
block = '/*regions:start*/\nconst REGIONS = ' + json.dumps([{'id': r, 'name': n, 'glaciers': [g['id'] for g in out if g['region'] == r and 'parent' not in g]} for r, n in REGION_NAMES], ensure_ascii=False, separators=(',', ':')) + ';\n/*regions:end*/'
gp = os.path.join(ROOT, 'gallery.html'); g = open(gp, encoding='utf-8').read()
a, z = g.index('/*regions:start*/'), g.index('/*regions:end*/') + len('/*regions:end*/')
open(gp, 'w', encoding='utf-8').write(g[:a] + block + g[z:])
