#!/usr/bin/env python3
"""Writes data/home-glaciers.js for the landing page (home.html): one record per glacier of every region, `window.HOME_GLACIERS`.
id = the id the dashboard takes in `#g=` (Swiss: the site id, see SITE_ID in audit_glaciers.py), name, region, area in km2 as the data
files state it (Swiss: SGI2023 `area_km2`; the others: `areaKm2` of the outlet), lat/lon = the tongue tip of data/boxes.js.
Also rewrites the marked block (regions) of gallery.html. Standard library only."""
import json, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SITE_ID = {'B36-26': 'aletsch', 'B56-07': 'gorner', 'B40-07': 'fiescher', 'A54g-11': 'unteraar', 'B83-03': 'corbassiere', 'B57-05': 'zmutt',
           'B43-03': 'rhone', 'B56-03': 'sgi-B56-03', 'B53-04': 'sgi-B53-04', 'A54e-24': 'trift'}
REGION_FILES = [('is-vatnajokull', 'vatnajokull'), ('is-rest', 'iceland'), ('no-mainland', 'norway'), ('no-svalbard', 'svalbard')]

def window(path, name):
    s = open(os.path.join(ROOT, path), encoding='utf-8').read()
    return json.JSONDecoder().raw_decode(s[s.index('{', s.index(name)):])[0]

boxes = window('data/boxes.js', 'window.GLACIER_BOXES')['glaciers']
out = []
swiss = {g['id']: g for g in window('data/glaciers.js', 'window.GLACIER_DATA')['glaciers']}
for inv, site in SITE_ID.items():
    b = boxes[inv]
    out.append({'id': site, 'name': b['name'], 'region': 'ch', 'area': swiss[inv]['area_km2'], 'tip': b['tip']})
for region, f in REGION_FILES:
    for o in window('data/%s.js' % f, 'window.REGION_ICE')['outlets']:
        out.append({'id': o['id'], 'name': o['name'], 'region': region, 'area': o['areaKm2'], 'tip': boxes[o['id']]['tip']})
path = os.path.join(ROOT, 'data', 'home-glaciers.js')
open(path, 'w', encoding='utf-8').write('// generated by scripts/build_home_glaciers.py - do not edit by hand\nwindow.HOME_GLACIERS = ' + json.dumps(out, ensure_ascii=False, separators=(',', ':')) + ';\n')
print(len(out), 'glaciers ->', path)

# gallery.html needs the same ids to tell the region of a shared item (items carry only the glacier id): rewrite its marked block
REGION_NAMES = [('ch', 'Switzerland'), ('is-vatnajokull', 'Vatnajökull'), ('is-rest', 'Rest of Iceland'), ('no-mainland', 'Mainland Norway'), ('no-svalbard', 'Svalbard')]
block = '/*regions:start*/\nconst REGIONS = ' + json.dumps([{'id': r, 'name': n, 'glaciers': [g['id'] for g in out if g['region'] == r]} for r, n in REGION_NAMES], ensure_ascii=False, separators=(',', ':')) + ';\n/*regions:end*/'
gp = os.path.join(ROOT, 'gallery.html'); g = open(gp, encoding='utf-8').read()
a, z = g.index('/*regions:start*/'), g.index('/*regions:end*/') + len('/*regions:end*/')
open(gp, 'w', encoding='utf-8').write(g[:a] + block + g[z:])
